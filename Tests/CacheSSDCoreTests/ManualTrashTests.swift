import XCTest
import Foundation
import Darwin
@testable import CacheSSDCore

final class ManualTrashTests: XCTestCase {
    private var root: URL!
    private var home: URL!
    private var store: Store!
    private var trashCalls = 0

    override func setUpWithError() throws {
        let parent = ProcessInfo.processInfo.environment["CACHESSD_TEST_TEMP"].map(URL.init(fileURLWithPath:)) ?? FileManager.default.temporaryDirectory
        root = Paths.physicalURL(parent).appendingPathComponent("DiskWing-manual-trash-\(UUID().uuidString)")
        home = root.appendingPathComponent("home")
        store = Store(base: root.appendingPathComponent("support"))
        try FileManager.default.createDirectory(at: home, withIntermediateDirectories: true)
        trashCalls = 0
    }

    override func tearDownWithError() throws { try? FileManager.default.removeItem(at: root) }

    @discardableResult private func file(_ relative: String, contents: String = "important generated bytes") throws -> URL {
        let item = home.appendingPathComponent(relative)
        try FileManager.default.createDirectory(at: item.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(contents.utf8).write(to: item)
        return item
    }

    private func fakeTrash(_ source: URL) throws -> URL? {
        trashCalls += 1
        let target = root.appendingPathComponent("trash/\(UUID().uuidString)/\(source.lastPathComponent)")
        try FileManager.default.createDirectory(at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
        try FileManager.default.moveItem(at: source, to: target)
        return target
    }

    private func actions(busyCheck: @escaping BusyCheck = { _, _ in [] }, checkpoint: @escaping (OperationJournal) throws -> Void = { _ in }) -> PersonalActions {
        PersonalActions(home: home, store: store, trashHandler: fakeTrash, busyCheck: busyCheck, checkpoint: checkpoint)
    }

    private func reason(_ item: URL, storeBase: URL? = nil) -> String? {
        PersonalActionPolicy.reasonPreventingTrash(item, home: home, storeBase: storeBase ?? store.base)
    }

    func testLibraryCacheCanBeTrashedButCannotBeRelocatedGenerically() throws {
        let source = try file("Library/Caches/com.example.generated/cache.db").deletingLastPathComponent()
        let before = try FileTree.digest(source)
        XCTAssertNil(reason(source))
        XCTAssertNotNil(PersonalActionPolicy.trashWarning(source, home: home))
        XCTAssertNotNil(PersonalActionPolicy.reasonPreventing(source, home: home))
        _ = try actions().trash(source, expectedIdentity: FileIdentity(source))
        XCTAssertEqual(trashCalls, 1)
        XCTAssertFalse(FileManager.default.fileExists(atPath: source.path))
        let journal = try XCTUnwrap(store.operations().first)
        XCTAssertEqual(journal.kind, "trash")
        XCTAssertEqual(journal.phase, .completed)
        XCTAssertEqual(journal.sourceDigest, before)
        XCTAssertEqual(try FileTree.digest(URL(fileURLWithPath: XCTUnwrap(journal.trashPath))), before)
    }

    func testUnknownApplicationDataRequiresWarningWithoutBeingClassifiedDisposable() throws {
        let source = try file("Library/Application Support/ExampleGeneratedApp/important-state.db")
        XCTAssertNil(reason(source))
        let warning = try XCTUnwrap(PersonalActionPolicy.trashWarning(source, home: home))
        XCTAssertTrue(warning.contains("informações"))
        XCTAssertNotNil(PersonalActionPolicy.reasonPreventing(source, home: home))
        _ = try actions().trash(source)
        XCTAssertEqual(trashCalls, 1)
    }

    func testSelectionBeyondOriginalSixFoldersCanBeReviewed() throws {
        let source = try file("custom-archives/old-export.bin")
        XCTAssertNil(reason(source))
        XCTAssertNotNil(PersonalActionPolicy.reasonPreventing(source, home: home))
        _ = try actions().trash(source)
        XCTAssertEqual(trashCalls, 1)
    }

    func testStructuralRootsSystemAndExternalPathsAreBlocked() throws {
        for relative in ["", "Library", "Library/Caches", "Library/Application Support", "Library/Containers", "Library/Group Containers", "Downloads", "Documents", ".config"] {
            XCTAssertNotNil(reason(home.appendingPathComponent(relative)), relative)
        }
        for item in [URL(fileURLWithPath: "/"), URL(fileURLWithPath: "/System"), root.appendingPathComponent("external-generation/cache")] {
            XCTAssertNotNil(reason(item), item.path)
        }
    }

    func testPrivateStoreItsDescendantsAndAncestorsArePreserved() throws {
        let privateBase = home.appendingPathComponent("custom-records/DiskWing")
        for item in [privateBase, privateBase.appendingPathComponent("operation.json"), privateBase.deletingLastPathComponent()] {
            XCTAssertNotNil(reason(item, storeBase: privateBase))
        }
        XCTAssertNotNil(PersonalActionPolicy.reasonPreventingTrash(home.appendingPathComponent("Library/Application Support/CacheSSD/history.json"), home: home))
        XCTAssertNil(reason(home.appendingPathComponent("custom-records/sibling-file"), storeBase: privateBase))
        XCTAssertNotNil(reason(home.appendingPathComponent("CUSTOM-RECORDS/diskwing/operation.json"), storeBase: privateBase))
    }

    func testCredentialsProfilesSDKsAndInstalledEnvironmentsArePreserved() throws {
        let protected = [
            ".ssh/generated_key", ".aws/credentials", ".config/gcloud/token", ".npmrc", "other/.env.production", "other/id_ed25519", ".codex/auth.json", ".docker/config.json", ".config/gh/hosts.yml",
            "Library/Keychains/generated.keychain-db", "Library/Application Support/Google/Chrome/Default/History",
            "Library/Developer/CoreSimulator/Devices/generated", "Library/Android/sdk/platform-tools/adb", ".android/avd/generated",
            ".bun/install/cache/generated/package.json", ".cache/uv/generated", ".local/share/uv/python/generated", ".npm/_npx/generated/run",
            ".gradle/wrapper/dists/generated", ".gradle/jdks/generated", "Documents/generated-project/.git/config", "Pictures/Generated.photoslibrary/database",
            "Library/Application Support/Google/CHROME/Default/History", "Documents/generated-project/.venv/pyvenv.cfg", "Documents/generated-project/node_modules/package/index.js"
        ]
        for relative in protected {
            let source = try file(relative)
            XCTAssertNotNil(reason(source), relative)
            XCTAssertThrowsError(try actions().trash(source), relative)
            XCTAssertEqual(try String(contentsOf: source), "important generated bytes")
        }
        XCTAssertEqual(trashCalls, 0)
        XCTAssertTrue(store.operations().isEmpty)
    }

    func testFolderContainingProtectedChildIsNotTrashed() throws {
        _ = try file("review-bundle/nested/.env", contents: "generated secret")
        let source = home.appendingPathComponent("review-bundle")
        XCTAssertNil(reason(source), "An inexpensive selection check is followed by full tree preflight")
        XCTAssertThrowsError(try actions().trash(source))
        XCTAssertEqual(trashCalls, 0)
        XCTAssertTrue(store.operations().isEmpty)
        XCTAssertEqual(try String(contentsOf: source.appendingPathComponent("nested/.env")), "generated secret")
    }

    func testRootAncestorAndDescendantLinksArePreserved() throws {
        let target = try file("real-cache/data").deletingLastPathComponent()
        let rootLink = home.appendingPathComponent("cache-link")
        try FileManager.default.createSymbolicLink(at: rootLink, withDestinationURL: target)
        XCTAssertNotNil(reason(rootLink))
        XCTAssertNotNil(reason(rootLink.appendingPathComponent("data")))
        let source = try file("Library/Caches/generated/ordinary").deletingLastPathComponent()
        try FileManager.default.createSymbolicLink(at: source.appendingPathComponent("nested-link"), withDestinationURL: target)
        XCTAssertThrowsError(try actions().trash(source))
        XCTAssertEqual(trashCalls, 0)
        XCTAssertEqual(try String(contentsOf: target.appendingPathComponent("data")), "important generated bytes")
    }

    func testCloudPlaceholderAndSpecialFileMetadataAreRejected() throws {
        // Local generated files cannot become genuine cloud placeholders without
        // a file provider. Exercise the production metadata seam explicitly.
        var metadata = stat()
        metadata.st_mode = S_IFREG | 0o600
        metadata.st_flags = UInt32(SF_DATALESS)
        XCTAssertNotNil(PersonalActionPolicy.trashMetadataReason(metadata))
        metadata.st_flags = 0
        XCTAssertNil(PersonalActionPolicy.trashMetadataReason(metadata))
        metadata.st_mode = S_IFIFO | 0o600
        XCTAssertNotNil(PersonalActionPolicy.trashMetadataReason(metadata))
        let fifo = home.appendingPathComponent("generated-fifo")
        XCTAssertEqual(mkfifo(fifo.path, 0o600), 0)
        XCTAssertThrowsError(try actions().trash(fifo))
        XCTAssertEqual(trashCalls, 0)
    }

    func testBusyCacheIsPreservedWithoutOperation() throws {
        let source = try file("Library/Caches/generated/data")
        let actions = actions(busyCheck: { _, _ in [BusyProcess(pid: 12345, name: "Generated client")] })
        XCTAssertThrowsError(try actions.trash(source))
        XCTAssertEqual(trashCalls, 0)
        XCTAssertTrue(store.operations().isEmpty)
        XCTAssertTrue(FileManager.default.fileExists(atPath: source.path))
    }

    func testChangedScannedIdentityPreservesCache() throws {
        let source = try file("Library/Caches/generated/data", contents: "old")
        let scanned = try FileIdentity(source)
        try Data("new version of generated file".utf8).write(to: source)
        XCTAssertThrowsError(try actions().trash(source, expectedIdentity: scanned))
        XCTAssertEqual(trashCalls, 0)
        XCTAssertEqual(try String(contentsOf: source), "new version of generated file")
    }

    func testMutationAtFinalTrashBoundaryPreservesNewBytes() throws {
        let source = try file("Library/Caches/generated/data").deletingLastPathComponent()
        var reachedBoundary = false
        let actions = actions(checkpoint: { journal in
            if journal.phase == .trashing {
                reachedBoundary = true
                try Data("changed during review".utf8).write(to: source.appendingPathComponent("data"))
            }
        })
        XCTAssertThrowsError(try actions.trash(source))
        XCTAssertTrue(reachedBoundary)
        XCTAssertEqual(trashCalls, 0)
        XCTAssertEqual(try String(contentsOf: source.appendingPathComponent("data")), "changed during review")
        XCTAssertEqual(store.operations().first?.phase, .interrupted)
    }

    func testPolicyIsRecheckedAfterFinalProcessInspection() throws {
        let source = try file("Library/Caches/generated/data").deletingLastPathComponent()
        var inspections = 0
        let actions = actions(busyCheck: { _, _ in
            inspections += 1
            if inspections == 2 { try Data("generated credential".utf8).write(to: source.appendingPathComponent(".env")) }
            return []
        })
        XCTAssertThrowsError(try actions.trash(source))
        XCTAssertEqual(inspections, 2)
        XCTAssertEqual(trashCalls, 0)
        XCTAssertEqual(try String(contentsOf: source.appendingPathComponent(".env")), "generated credential")
        XCTAssertEqual(store.operations().first?.phase, .interrupted)
    }

    func testUnreadableCacheIsNotTrashed() throws {
        let source = try file("Library/Caches/generated/data").deletingLastPathComponent()
        try FileManager.default.setAttributes([.posixPermissions: 0o000], ofItemAtPath: source.path)
        defer { try? FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: source.path) }
        XCTAssertThrowsError(try actions().trash(source))
        XCTAssertEqual(trashCalls, 0)
    }

    func testLimitedAndCancelledTrashPreflightPreservesCache() throws {
        let source = home.appendingPathComponent("Library/Caches/generated")
        for index in 0..<250 { try file("Library/Caches/generated/file-\(index)") }
        let before = try FileTree.digest(source), cancellation = CancellationFlag()
        XCTAssertThrowsError(try PersonalActionPolicy.validateTrashTree(source, home: home, storeBase: store.base, cancellation: cancellation, maxEntries: 40))
        XCTAssertThrowsError(try PersonalActionPolicy.validateTrashTree(source, home: home, storeBase: store.base, cancellation: cancellation, progress: { _ in cancellation.cancel() }))
        XCTAssertTrue(cancellation.isCancelled)
        XCTAssertThrowsError(try actions().trash(source, cancellation: cancellation))
        XCTAssertEqual(trashCalls, 0)
        XCTAssertTrue(store.operations().isEmpty)
        XCTAssertEqual(try FileTree.digest(source), before)
    }

    private func interruptedCacheTrash() throws -> (URL, OperationJournal, String) {
        let source = try file("Library/Caches/generated/data").deletingLastPathComponent()
        let before = try FileTree.digest(source)
        var reachedPublication = false
        let actions = actions(checkpoint: { journal in
            if journal.phase == .published { reachedPublication = true; throw CacheSSDError.message("generated failure after Trash publication") }
        })
        XCTAssertThrowsError(try actions.trash(source))
        XCTAssertTrue(reachedPublication)
        XCTAssertFalse(FileManager.default.fileExists(atPath: source.path))
        let journal = try XCTUnwrap(store.operations().first)
        XCTAssertEqual(journal.phase, .interrupted)
        XCTAssertEqual(journal.sourceDigest, before)
        return (source, journal, before)
    }

    func testInterruptedLibraryCacheTrashCanRecoverMissingSource() throws {
        let (source, journal, before) = try interruptedCacheTrash()
        XCTAssertNil(reason(source))
        let recovery = RecoveryManager(store: store, home: home, busyCheck: { _, _ in [] })
        XCTAssertTrue(try XCTUnwrap(recovery.pending().first).canRestoreSource)
        try recovery.restoreSource(id: journal.id)
        XCTAssertEqual(try FileTree.digest(source), before)
        XCTAssertEqual(store.operations().first?.phase, .resolved)
        XCTAssertEqual(try FileTree.digest(URL(fileURLWithPath: XCTUnwrap(journal.trashPath))), before)
    }

    func testDirectoryHintsDoNotChangeExistingOrAbsentTrashEligibility() throws {
        let source = try file("Library/Caches/generated/data").deletingLastPathComponent()
        let directory = URL(fileURLWithPath: source.path, isDirectory: true)
        let fileHint = URL(fileURLWithPath: source.path, isDirectory: false)
        XCTAssertTrue(directory.hasDirectoryPath)
        XCTAssertFalse(fileHint.hasDirectoryPath)
        XCTAssertEqual(directory.path, fileHint.path)
        for item in [directory, fileHint] { XCTAssertNil(reason(item)) }
        try FileManager.default.removeItem(at: source)
        for item in [directory, fileHint] { XCTAssertNil(reason(item), "An absent source is assessed by its path, not its stale directory hint") }
        for hint in [true, false] {
            XCTAssertNotNil(reason(URL(fileURLWithPath: home.path, isDirectory: hint)), "The home root stays protected for either URL hint")
        }
    }

    func testInterruptedTrashRecoversForBothDirectoryHints() throws {
        for hint in [true, false] {
            let (source, journal, before) = try interruptedCacheTrash()
            let hintedSource = URL(fileURLWithPath: source.path, isDirectory: hint)
            let hintedHome = URL(fileURLWithPath: home.path, isDirectory: hint)
            XCTAssertNil(PersonalActionPolicy.reasonPreventingTrash(hintedSource, home: hintedHome, storeBase: store.base))
            try RecoveryManager(store: store, home: hintedHome, busyCheck: { _, _ in [] }).restoreSource(id: journal.id)
            XCTAssertEqual(try FileTree.digest(source), before)
            XCTAssertEqual(store.operations().first(where: { $0.id == journal.id })?.phase, .resolved)
        }
    }

    func testAbsentDirectoryHintsDoNotHideRedirectedAncestor() throws {
        let source = try file("Library/Caches/generated/data").deletingLastPathComponent()
        try FileManager.default.removeItem(at: source)
        let library = home.appendingPathComponent("Library"), retained = home.appendingPathComponent("retained-library")
        try FileManager.default.moveItem(at: library, to: retained)
        try FileManager.default.createSymbolicLink(at: library, withDestinationURL: retained)
        for hint in [true, false] {
            XCTAssertNotNil(reason(URL(fileURLWithPath: source.path, isDirectory: hint)), "An absent leaf must not hide an existing symbolic ancestor")
        }
    }

    func testRecoveryDoesNotOverwriteRecreatedCache() throws {
        let (source, journal, before) = try interruptedCacheTrash()
        try FileManager.default.createDirectory(at: source, withIntermediateDirectories: true)
        try Data("recreated by app".utf8).write(to: source.appendingPathComponent("new-data"))
        XCTAssertThrowsError(try RecoveryManager(store: store, home: home, busyCheck: { _, _ in [] }).restoreSource(id: journal.id))
        XCTAssertEqual(try String(contentsOf: source.appendingPathComponent("new-data")), "recreated by app")
        XCTAssertEqual(try FileTree.digest(URL(fileURLWithPath: XCTUnwrap(journal.trashPath))), before)
    }

    func testRecoveryRejectsRedirectedAbsentSourceParent() throws {
        let (source, journal, before) = try interruptedCacheTrash()
        let library = home.appendingPathComponent("Library"), retained = home.appendingPathComponent("retained-library")
        try FileManager.default.moveItem(at: library, to: retained)
        try FileManager.default.createSymbolicLink(at: library, withDestinationURL: retained)
        XCTAssertThrowsError(try RecoveryManager(store: store, home: home, busyCheck: { _, _ in [] }).restoreSource(id: journal.id))
        XCTAssertFalse(FileManager.default.fileExists(atPath: source.path))
        XCTAssertEqual(try FileTree.digest(URL(fileURLWithPath: XCTUnwrap(journal.trashPath))), before)
    }

    func testRecoveryRechecksAbsentParentAfterCopyProcessInspection() throws {
        let (source, journal, before) = try interruptedCacheTrash()
        let library = home.appendingPathComponent("Library"), retained = home.appendingPathComponent("retained-library")
        let copy = try XCTUnwrap(journal.trashPath)
        var reachedInspection = false
        let recovery = RecoveryManager(store: store, home: home, busyCheck: { paths, _ in
            XCTAssertEqual(paths.map(\.path), [copy])
            reachedInspection = true
            try FileManager.default.moveItem(at: library, to: retained)
            try FileManager.default.createSymbolicLink(at: library, withDestinationURL: retained)
            return []
        })
        XCTAssertThrowsError(try recovery.restoreSource(id: journal.id))
        XCTAssertTrue(reachedInspection)
        XCTAssertFalse(FileManager.default.fileExists(atPath: source.path))
        XCTAssertFalse(try FileManager.default.contentsOfDirectory(atPath: retained.appendingPathComponent("Caches").path).contains(where: { $0.hasPrefix(".CacheSSD-recovery-") }))
        XCTAssertEqual(try FileTree.digest(URL(fileURLWithPath: copy)), before)
    }

    func testPersonalMoveJournalDoesNotInheritWiderTrashScope() throws {
        let source = try file("Library/Caches/generated/data").deletingLastPathComponent()
        var journal = try OperationJournal(kind: "personalMove", source: source)
        journal.sourceDigest = try FileTree.digest(source)
        journal.trashPath = try fakeTrash(source)?.path
        journal.phase = .interrupted
        try store.writeDurably(journal, name: "operation-\(journal.id.uuidString).json")
        XCTAssertThrowsError(try RecoveryManager(store: store, home: home, busyCheck: { _, _ in [] }).restoreSource(id: journal.id))
        XCTAssertFalse(FileManager.default.fileExists(atPath: source.path))
        XCTAssertTrue(FileManager.default.fileExists(atPath: try XCTUnwrap(journal.trashPath)))
    }
}
